def load_model_features():
    """
    Load the finalized feature table generated by
    feature engineering.
    """

    df = pd.read_csv(FEATURES_PATH)

    required_columns = [
        "invoice_id",
        *MODEL_FEATURES
    ]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            f"Missing required model features: {missing}"
        )

    return df[required_columns].copy()


def get_model_input(df):
    """
    Return only the numerical features required
    by the Isolation Forest model.
    """

    return df[MODEL_FEATURES].copy()